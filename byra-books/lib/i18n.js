const Ctx = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState('id');

  useEffect(() => {
    try {
      const saved = localStorage.getItem('byra_lang');
      if (saved === 'id' || saved === 'en') setLangState(saved);
    } catch {
      /* ignore */
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo(() => {
    const setLang = (l) => {
      setLangState(l);
      try { localStorage.setItem('byra_lang', l); } catch { /* ignore */ }
    };
    const t = (key, vars) => {
      let text = DICT[lang]?.[key] ?? DICT.id[key] ?? key;
      if (vars) {
        Object.entries(vars).forEach(([k, v]) => {
          text = text.split(`{${k}}`).join(String(v));
        });
      }
      return text;
    };
    const pick = (obj, base) => obj?.[`${base}_${lang}`] || obj?.[base] || '';
    return { lang, setLang, t, pick };
  }, [lang]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
